// Global Translation Helper (Upgraded with Fallback support)
window.t = function(key, fallbackText = "") {
    const lang = localStorage.getItem('mnotes_lang') || 'en';
    const otherLang = lang === 'en' ? 'el' : 'en';
    if (typeof TRANSLATIONS !== 'undefined') {
        if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) return TRANSLATIONS[lang][key];
    }
    if (fallbackText) return fallbackText;
    if (typeof TRANSLATIONS !== 'undefined') {
        if (TRANSLATIONS[otherLang] && TRANSLATIONS[otherLang][key]) return TRANSLATIONS[otherLang][key];
    }
    return key;
}

